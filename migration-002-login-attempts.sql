-- Migration: Rate limiting table for login attempts
-- Creates public.login_attempts table with indexes for fast IP-based lookups

create table if not exists public.login_attempts (
    id bigint generated by default as identity primary key,
    ip text not null,
    scope text not null, -- 'admin' or 'teacher'
    attempted_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_login_attempts_ip_scope on public.login_attempts(ip, scope, attempted_at desc);

-- Enable RLS (only service_role can read/write)
alter table public.login_attempts enable row level security;
